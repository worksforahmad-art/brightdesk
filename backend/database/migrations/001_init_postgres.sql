-- BrightDesk PostgreSQL schema for Supabase.
-- Run ONCE in Supabase > SQL Editor before setting DATABASE_URL on Railway.
-- Safe to rerun: existing users/sessions are not deleted.
-- BrightDesk authenticates through its server (not Supabase Auth).

CREATE TABLE IF NOT EXISTS public.users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    username TEXT NOT NULL,
    email TEXT NOT NULL,
    password TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_username_unique UNIQUE (username),
    CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS public.sessions (
    sid TEXT PRIMARY KEY,
    sess TEXT NOT NULL,
    expired_at BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS sessions_expired_at_idx
    ON public.sessions (expired_at);

-- These tables hold hashed passwords and authenticated session payloads.
-- The BrightDesk backend connects over PostgreSQL; never expose them through
-- Supabase's anon/authenticated Data API roles.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.users, public.sessions FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.users_id_seq FROM anon, authenticated;
